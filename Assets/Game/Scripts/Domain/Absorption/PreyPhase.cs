namespace PM.Domain.Absorption {
/// <summary>Состояния добычи (ABSORPTION_GENETICS). Переходы строго по событиям, без пропусков.</summary>
public enum PreyPhase {
    Free = 0,        // жива, в мире
    Weakened = 1,    // здоровье ниже порога, может быть захвачена
    Captured = 2,    // удерживается (прогресс растёт)
    Internalized = 3,// во внутренней среде (запись в камере, не физический объект)
    Digesting = 4,   // переваривается по игровому времени
    Consumed = 5     // разобрана: компоненты+гены выданы однократно
}
}
